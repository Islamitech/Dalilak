/**
 * Check if a coordinate is inside a polygon ring (Ray-Casting Algorithm)
 */
export function isPointInPolygon(lat: number, lng: number, polygon: [number, number][]): boolean {
  let inside = false;
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const xi = polygon[i][0], yi = polygon[i][1];
    const xj = polygon[j][0], yj = polygon[j][1];
    const intersect = ((yi > lng) !== (yj > lng)) &&
      (lat < ((xj - xi) * (lng - yi)) / (yj - yi) + xi);
    if (intersect) inside = !inside;
  }
  return inside;
}

/**
 * Determine which Hadayek district a point (lat, lng) belongs to
 */
export function findDistrictForCoordinates(lat: number, lng: number): HadayekOfficialDistrict | null {
  for (const district of HADAYEK_OFFICIAL_DISTRICTS) {
    for (const poly of district.polygons) {
      if (isPointInPolygon(lat, lng, poly)) {
        return district;
      }
    }
  }
  return null;
}

/**
 * Get district by letter (e.g. 'أ', 'ب', 'ل', 'هـ')
 */
export function getDistrictByLetter(letter: string): HadayekOfficialDistrict | undefined {
  if (!letter) return undefined;
  const clean = letter.replace(/^منطقة\s+/, '').trim();
  const normalize = (s: string) => s.replace(/[أإآ]/g, 'ا').replace(/ة/g, 'ه').replace(/هـ/g, 'ه').trim();
  const normClean = normalize(clean);

  return HADAYEK_OFFICIAL_DISTRICTS.find((d) => {
    return (
      d.letterAr === clean ||
      normalize(d.letterAr) === normClean ||
      d.nameAr === letter ||
      normalize(d.nameAr) === normalize(letter) ||
      d.nameEn.toLowerCase() === clean.toLowerCase()
    );
  });
}

