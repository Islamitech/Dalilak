export function getPackageById(packageId?: string | null): PackageOption | undefined {
  if (!packageId) return undefined;
  if (packageId === EXEMPT_PACKAGE.id) return EXEMPT_PACKAGE;
  if (packageId === ALREADY_ON_GOOGLE_PACKAGE.id) return ALREADY_ON_GOOGLE_PACKAGE;
  return PACKAGES.find((p) => p.id === packageId);
}

export function isExemptPackage(packageId?: string | null): boolean {
  return packageId === EXEMPT_PACKAGE.id || packageId === ALREADY_ON_GOOGLE_PACKAGE.id;
}
