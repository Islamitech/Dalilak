export function getMotivationalGroupByBusiness(biz: Business): CategoryMotivationalGroup {
  const bizCategory = biz.category || '';
  const detectedGroup = getGroupFromCategory(bizCategory);
  
  if (detectedGroup) {
    const match = CATEGORY_MOTIVATIONAL_DATA.find((g) => g.groupName === detectedGroup.group);
    if (match) return match;
  }

  const byKeyword = CATEGORY_MOTIVATIONAL_DATA.find((g) => {
    return bizCategory.includes(g.groupName) || g.groupName.includes(bizCategory);
  });

  return byKeyword || CATEGORY_MOTIVATIONAL_DATA[0];
}

export function getCategoryMotivationalWhatsAppUrl(model: CategoryMotivationalModel, biz: Business): string {
  const phone = formatWhatsAppPhone(biz.ownerPhone || biz.phone);
  const text = safeWhatsAppEncode(model.generateText(biz));
  return `https://wa.me/${phone}?text=${text}`;
}
